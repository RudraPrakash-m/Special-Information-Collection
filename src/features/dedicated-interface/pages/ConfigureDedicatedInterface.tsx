/*  */import React, { useState, useMemo } from 'react';
import { useNavigate, useSearchParams } from 'react-router-dom';
import {
  Eye,
  Save,
  Copy,
  Check,
  RotateCcw,
} from 'lucide-react';
import { Button, DataTable } from '@/shared/components/ui';
import Card from '@/shared/components/layout/Card';
import PageHeader from '@/shared/components/layout/PageHeader';
import {
  FormGenerator,
  SearchableSelect,
  UploadFile,
  TextArea,
  type FormField,
} from '@/shared/components/ui/Forms';
import FieldInfoTooltip from '@/features/create-collection/components/FieldInfoTooltip';
import formFieldsJson from '../form-config/dedicatedInterfaceForm.json';
import {
  type DedicatedInterfaceConfig,
  getLinkStatus,
} from '../types/dedicatedInterface.types';
import { useCollectionStore } from '@/features/collection-store/CollectionStore';
import { useConfirmDialog } from '@/features/collection-store/useConfirmDialog';
import { toast } from 'sonner';
import { getDedicatedInterfaceColumns, LINK_STATUS_HINT } from '../columns/dedicatedInterfaceColumns';
import { validateDedicatedInterface } from '../validation/dedicatedInterfaceValidation';

const FIELD_TOOLTIPS: Record<string, { tooltip: string; example?: string }> = {
  collectionId: {
    tooltip: 'Collection for which the dedicated interface is configured.',
  },
  linkName: {
    tooltip:
      'Readable part of the dedicated link (slug). Mandatory; lower-case letters, numbers and hyphens; unique.',
    example: 'nss-volunteers-2026',
  },
  dedicatedLink: {
    tooltip: 'Full link generated by the system. Active after the collection is published.',
  },
  helpdeskContact: {
    tooltip: 'Name, phone and e-mail for queries.',
    example: 'Dr. S. Pattnaik | 0674-2391244 | nodal-hims@odisha.gov.in',
  },
  pageHeading: {
    tooltip: 'Heading displayed on the landing page (maximum 200 characters).',
    example: 'Quarterly Degree College Academic & Lab Infrastructure Self-Appraisal',
  },
  downloads: {
    tooltip:
      'Reference document and prescribed format. Optional; PDF / XLSX / DOCX; maximum 10 MB each.',
  },
  showAsDedicatedMenu: {
    tooltip: 'Shows the collection as a separate menu item for users of target institutions.',
  },
  instructions: {
    tooltip: 'Instructions displayed on the landing page (maximum 2000 characters).',
  },
};

export const ConfigureDedicatedInterface: React.FC = () => {
  const navigate = useNavigate();
  const [searchParams] = useSearchParams();
  const initialCollectionParam = searchParams.get('collectionId');

  // Master collections
  const { collections, interfaces, setInterfaces } = useCollectionStore();

  // Empty initial form state (NO dummy prefilled texts)
  const [editingInterfaceId, setEditingInterfaceId] = useState<string | null>(null);
  const { confirm, confirmDialog } = useConfirmDialog();
  const [isCopied, setIsCopied] = useState(false);

  const [formData, setFormData] = useState<{
    collectionId: string;
    linkName: string;
    dedicatedLink: string;
    helpdeskContact: string;
    pageHeading: string;
    instructions: string;
    downloads: File | string | null;
    showAsDedicatedMenu: boolean;
  }>({
    collectionId: initialCollectionParam || '',
    linkName: '',
    dedicatedLink: '',
    helpdeskContact: '',
    pageHeading: '',
    instructions: '',
    downloads: null,
    showAsDedicatedMenu: false,
  });

  // If initialCollectionParam is provided and has an existing configuration, load it
  React.useEffect(() => {
    if (initialCollectionParam) {
      const existing = interfaces.find((item) => item.collectionId === initialCollectionParam);
      if (existing) {
        setEditingInterfaceId(existing.id);
        setFormData({
          collectionId: existing.collectionId,
          linkName: existing.linkName,
          dedicatedLink: existing.dedicatedLink,
          helpdeskContact: existing.helpdeskContact,
          pageHeading: existing.pageHeading,
          instructions: existing.instructions,
          downloads: existing.downloadFileName || null,
          showAsDedicatedMenu: existing.showAsDedicatedMenu,
        });
      }
    }
  }, [initialCollectionParam, interfaces]);

  // When collection is chosen from the dropdown:
  const handleCollectionSelect = (colId: string) => {
    const existing = interfaces.find((item) => item.collectionId === colId);
    if (existing) {
      setEditingInterfaceId(existing.id);
      setFormData({
        collectionId: existing.collectionId,
        linkName: existing.linkName,
        dedicatedLink: existing.dedicatedLink,
        helpdeskContact: existing.helpdeskContact,
        pageHeading: existing.pageHeading,
        instructions: existing.instructions,
        downloads: existing.downloadFileName || null,
        showAsDedicatedMenu: existing.showAsDedicatedMenu,
      });
      toast.info(`Loaded existing configuration for ${existing.collectionTitle}.`);
    } else {
      setEditingInterfaceId(null);
      setFormData({
        collectionId: colId,
        linkName: '',
        dedicatedLink: '',
        helpdeskContact: '',
        pageHeading: '',
        instructions: '',
        downloads: null,
        showAsDedicatedMenu: false,
      });
    }
  };

  // Copy full URL
  const handleCopyLink = (url: string) => {
    if (!formData.linkName.trim()) {
      toast.error('Please enter a Link Name first.');
      return;
    }
    navigator.clipboard.writeText(url).then(
      () => {
        setIsCopied(true);
        toast.success('Dedicated link copied to clipboard!');
        setTimeout(() => setIsCopied(false), 2000);
      },
      () => toast.error('Failed to copy to clipboard.')
    );
  };

  // Reset form to blank
  const handleResetForm = () => {
    setEditingInterfaceId(null);
    setFormData({
      collectionId: '',
      linkName: '',
      dedicatedLink: '',
      helpdeskContact: '',
      pageHeading: '',
      instructions: '',
      downloads: null,
      showAsDedicatedMenu: false,
    });
    toast.info('Form cleared.');
  };

  // Validate form
  const validateForm = (): boolean => {
    const valResult = validateDedicatedInterface({
      collectionId: formData.collectionId,
      linkName: formData.linkName,
      pageHeading: formData.pageHeading,
    });
    if (!valResult.isValid) {
      toast.error(Object.values(valResult.errors)[0]);
      return false;
    }
    return true;
  };

  // Save interface
  const handleSaveInterface = () => {
    if (!validateForm()) return;

    const fullUrl = `https://himsplus.odisha.gov.in/portal/collection/${formData.linkName.trim()}`;
    const selectedCol = collections.find((c) => c.id === formData.collectionId);

    let downloadName = '';
    if (typeof formData.downloads === 'string') {
      downloadName = formData.downloads;
    } else if (formData.downloads instanceof File) {
      downloadName = formData.downloads.name;
    }

    const newConfig: DedicatedInterfaceConfig = {
      id: editingInterfaceId || `INTF-2026-${String(interfaces.length + 1).padStart(3, '0')}`,
      collectionId: formData.collectionId,
      collectionTitle: selectedCol?.collectionTitle || 'Information Collection',
      linkName: formData.linkName.trim(),
      dedicatedLink: fullUrl,
      pageHeading: formData.pageHeading.trim(),
      instructions: formData.instructions.trim(),
      downloadFileName: downloadName || undefined,
      helpdeskContact: formData.helpdeskContact.trim(),
      showAsDedicatedMenu: formData.showAsDedicatedMenu,
      createdAt: new Date().toISOString().split('T')[0],
      updatedAt: new Date().toISOString().split('T')[0],
    };

    setInterfaces((prev) => {
      const filtered = prev.filter((item) => item.collectionId !== formData.collectionId);
      return [newConfig, ...filtered];
    });

    // Stay on the page with the saved interface open for editing.
    setEditingInterfaceId(newConfig.id);
    toast.success(`Dedicated Interface for "${newConfig.collectionTitle}" saved successfully!`);
  };

  // Preview the landing page in a new tab, so the form keeps its values
  const handlePreview = () => {
    if (!validateForm()) return;
    window.open(`/portal/collection/${formData.linkName.trim()}?preview=true`, '_blank', 'noopener');
  };

  // Edit existing row from table
  const handleEdit = (r: DedicatedInterfaceConfig) => {
    setEditingInterfaceId(r.id);
    setFormData({
      collectionId: r.collectionId,
      linkName: r.linkName,
      dedicatedLink: r.dedicatedLink,
      helpdeskContact: r.helpdeskContact,
      pageHeading: r.pageHeading,
      instructions: r.instructions,
      downloads: r.downloadFileName || null,
      showAsDedicatedMenu: r.showAsDedicatedMenu,
    });
    window.scrollTo({ top: 0, behavior: 'smooth' });
    toast.info(`Editing interface for ${r.collectionTitle}.`);
  };

  // Delete interface from table
  const handleDelete = (id: string) => {
    setInterfaces((prev) => prev.filter((item) => item.id !== id));
    if (editingInterfaceId === id) {
      handleResetForm();
    }
    toast.success('Interface configuration deleted.');
  };

  // The dedicated link is active only after the selected collection is published
  const linkStatus = getLinkStatus(collections.find((c) => c.id === formData.collectionId)?.status);

  // Collection options for SearchableSelect
  const collectionOptions = useMemo(() => {
    return collections.map((c) => ({
      label: `${c.collectionTitle} (${c.id})`,
      value: c.id,
    }));
  }, [collections]);

  // Dynamic Form Fields with FieldInfoTooltip and NO placeholders
  const dynamicFormFields: FormField[] = useMemo(() => {
    return (formFieldsJson as FormField[]).map((field) => {
      const info = FIELD_TOOLTIPS[field.name];

      // 1. Collection (SearchableSelect, col-span-3)
      if (field.name === 'collectionId') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void, error?: string) => (
            <div className="col-span-12 sm:col-span-6 md:col-span-3">
              <FieldInfoTooltip
                label="Collection"
                required={true}
                tooltipText={info?.tooltip || ''}
              />
              <SearchableSelect
                options={collectionOptions}
                value={value ?? ''}
                onChange={(val) => {
                  onChange(val);
                  handleCollectionSelect(String(val));
                }}
                placeholder="- Select -"
                error={error}
              />
            </div>
          ),
        };
      }

      // 2. Link Name (col-span-3)
      if (field.name === 'linkName') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void, error?: string) => (
            <div className="col-span-12 sm:col-span-6 md:col-span-3">
              <FieldInfoTooltip
                label="Link Name"
                required={true}
                tooltipText={info?.tooltip || ''}
                exampleText={info?.example}
              />
              <input
                type="text"
                value={value ?? ''}
                onChange={(e) => {
                  const cleaned = e.target.value.toLowerCase().replace(/[^a-z0-9-]/g, '');
                  onChange(cleaned);
                  setFormData((prev) => ({
                    ...prev,
                    linkName: cleaned,
                    dedicatedLink: cleaned
                      ? `https://himsplus.odisha.gov.in/portal/collection/${cleaned}`
                      : '',
                  }));
                }}
                placeholder=""
                className={`ui-field ${error ? 'ui-field--error' : ''}`}
              />
              {error && <p className="ui-error mt-1">{error}</p>}
            </div>
          ),
        };
      }

      // 3. Dedicated Link (Read-only, col-span-3 with Copy button)
      if (field.name === 'dedicatedLink') {
        return {
          ...field,
          placeholder: '',
          render: () => {
            const currentUrl = formData.linkName
              ? `https://himsplus.odisha.gov.in/portal/collection/${formData.linkName}`
              : 'https://himsplus.odisha.gov.in/portal/collection/...';
            return (
              <div className="col-span-12 sm:col-span-6 md:col-span-3">
                <FieldInfoTooltip
                  label="Dedicated Link"
                  tooltipText={info?.tooltip || ''}
                />
                <div className="relative">
                  <input
                    type="text"
                    readOnly
                    value={currentUrl}
                    className="ui-field bg-muted/40 font-mono text-xs pr-8 text-muted-foreground select-all cursor-default"
                  />
                  <button
                    type="button"
                    onClick={() => handleCopyLink(currentUrl)}
                    title="Copy Dedicated Link"
                    className="absolute right-2.5 top-1/2 -translate-y-1/2 text-muted-foreground hover:text-foreground transition-colors cursor-pointer"
                  >
                    {isCopied ? (
                      <Check size={14} className="text-emerald-600" />
                    ) : (
                      <Copy size={14} />
                    )}
                  </button>
                </div>
                {formData.collectionId && (
                  <p
                    className={`mt-1 text-[11px] ${
                      linkStatus === 'Active'
                        ? 'text-emerald-700 dark:text-emerald-400'
                        : 'text-muted-foreground'
                    }`}
                  >
                    {LINK_STATUS_HINT[linkStatus]}
                  </p>
                )}
              </div>
            );
          },
        };
      }

      // 4. Helpdesk Contact (col-span-3)
      if (field.name === 'helpdeskContact') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void, error?: string) => (
            <div className="col-span-12 sm:col-span-6 md:col-span-3">
              <FieldInfoTooltip
                label="Helpdesk Contact"
                tooltipText={info?.tooltip || ''}
                exampleText={info?.example}
              />
              <input
                type="text"
                value={value ?? ''}
                onChange={(e) => {
                  onChange(e.target.value);
                  setFormData((prev) => ({ ...prev, helpdeskContact: e.target.value }));
                }}
                placeholder=""
                className={`ui-field ${error ? 'ui-field--error' : ''}`}
              />
              {error && <p className="ui-error mt-1">{error}</p>}
            </div>
          ),
        };
      }

      // 5. Page Heading (col-span-6)
      if (field.name === 'pageHeading') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void, error?: string) => (
            <div className="col-span-12 sm:col-span-12 md:col-span-6">
              <FieldInfoTooltip
                label="Page Heading"
                required={true}
                tooltipText={info?.tooltip || ''}
                exampleText={info?.example}
              />
              <input
                type="text"
                maxLength={200}
                value={value ?? ''}
                onChange={(e) => {
                  onChange(e.target.value);
                  setFormData((prev) => ({ ...prev, pageHeading: e.target.value }));
                }}
                placeholder=""
                className={`ui-field ${error ? 'ui-field--error' : ''}`}
              />
              {error && <p className="ui-error mt-1">{error}</p>}
            </div>
          ),
        };
      }

      // 6. Downloads (UploadFile, col-span-3)
      if (field.name === 'downloads') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void, error?: string) => (
            <div className="col-span-12 sm:col-span-6 md:col-span-3">
              <FieldInfoTooltip
                label="Downloads"
                tooltipText={info?.tooltip || ''}
              />
              <UploadFile
                value={value as File | string | null}
                onChange={(file) => {
                  onChange(file);
                  setFormData((prev) => ({ ...prev, downloads: file }));
                }}
                accept=".pdf,.xlsx,.docx"
                error={error}
              />
            </div>
          ),
        };
      }

      // 7. Show as Dedicated Menu (Checkbox, col-span-3)
      if (field.name === 'showAsDedicatedMenu') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void) => (
            <div className="col-span-12 sm:col-span-6 md:col-span-3">
              <FieldInfoTooltip
                label="Show as Dedicated Menu"
                tooltipText={info?.tooltip || ''}
              />
              <label className="flex items-center gap-2 h-9 text-xs font-medium text-foreground cursor-pointer select-none">
                <input
                  type="checkbox"
                  checked={Boolean(value)}
                  onChange={(e) => {
                    onChange(e.target.checked);
                    setFormData((prev) => ({ ...prev, showAsDedicatedMenu: e.target.checked }));
                  }}
                  className="ui-check"
                />
                <span>Show this link as a dedicated menu</span>
              </label>
            </div>
          ),
        };
      }

      // 8. Instructions (TextArea, col-span-12)
      if (field.name === 'instructions') {
        return {
          ...field,
          placeholder: '',
          render: (value: any, onChange: (val: any) => void, error?: string) => (
            <div className="col-span-12">
              <FieldInfoTooltip
                label="Instructions"
                tooltipText={info?.tooltip || ''}
              />
              <TextArea
                rows={3}
                maxLength={2000}
                value={value ?? ''}
                onChange={(e) => {
                  onChange(e.target.value);
                  setFormData((prev) => ({ ...prev, instructions: e.target.value }));
                }}
                placeholder=""
                className={error ? 'ui-field--error' : ''}
              />
              {error && <p className="ui-error mt-1">{error}</p>}
            </div>
          ),
        };
      }

      return field;
    });
  }, [collectionOptions, formData.linkName, formData.collectionId, isCopied, linkStatus]);

  const tableColumns = useMemo(
    () =>
      getDedicatedInterfaceColumns({
        onEdit: (r) =>
          confirm({
            title: 'Edit Dedicated Interface',
            message: `Load the interface for "${r.collectionTitle}" into the form for editing?`,
            confirmText: 'Edit',
            onConfirm: () => handleEdit(r),
          }),
        onDelete: (id) =>
          confirm({
            title: 'Delete Dedicated Interface',
            message: `Delete interface configuration ${id}? This cannot be undone.`,
            confirmText: 'Delete',
            type: 'danger',
            onConfirm: () => handleDelete(id),
          }),
        onCopyLink: (r) => {
          navigator.clipboard.writeText(r.dedicatedLink);
          toast.success('Dedicated portal link copied to clipboard!');
        },
        onPreview: (linkName) => {
          navigate(`/portal/collection/${linkName}?preview=true`);
        },
        getCollectionStatus: (collectionId) => collections.find((c) => c.id === collectionId)?.status,
      }),
    [navigate, collections]
  );

  return (
    <div className="space-y-6 max-w-7xl mx-auto pb-12">
      {/* PAGE HEADER */}
      <PageHeader
        title="Configure Dedicated Link and Interface"
        breadcrumbs={[{ label: 'Dedicated Interface' }]}
      />

      {/* MAIN CARD: Clean Reusable Form without extra clutter */}
      <Card
        title={
          editingInterfaceId
            ? 'Edit Dedicated Link and Landing Page'
            : 'Configure Dedicated Link and Landing Page'
        }
        actions={
          editingInterfaceId ? (
            <Button
              type="button"
              variant="outline"
              size="sm"
              leftIcon={RotateCcw}
              onClick={handleResetForm}
            >
              Cancel Edit
            </Button>
          ) : undefined
        }
      >
        <FormGenerator
          formId="dedicated-interface-form"
          key={editingInterfaceId || 'new'}
          fields={dynamicFormFields}
          defaultValues={formData}
          onValuesChange={(vals) => setFormData((prev) => ({ ...prev, ...vals }))}
          onSubmit={handleSaveInterface}
          gridColumns={12}
        />

        {/* Form Action Buttons (SRS 1.3: Preview / Save): Inside the Card and Start Aligned */}
        <div className="flex flex-wrap items-center justify-start gap-3 pt-5 border-t border-border mt-6">
          <Button
            type="button"
            variant="outline"
            leftIcon={Eye}
            onClick={handlePreview}
          >
            Preview
          </Button>

          {editingInterfaceId && (
            <Button
              type="button"
              variant="outline"
              leftIcon={RotateCcw}
              onClick={handleResetForm}
            >
              Cancel Edit
            </Button>
          )}

          <Button
            type="submit"
            form="dedicated-interface-form"
            variant="primary"
            leftIcon={Save}
          >
            {editingInterfaceId ? 'Update' : 'Save'}
          </Button>
        </div>
      </Card>

      {/* Configured Dedicated Interfaces Table inside Card */}
      <Card title="Configured Dedicated Interfaces">
        <DataTable
          caption="Configured Dedicated Interfaces"
          data={interfaces}
          columns={tableColumns}
          rowKey={(r) => r.id}
          searchPlaceholder="Search interface, collection, or slug..."
          emptyTitle="No Dedicated Interfaces Configured"
          emptyDescription="Use the form above to configure a dedicated slug, instructions, and download formats for any collection."
        />
      </Card>

      {confirmDialog}
    </div>
  );
};

export default ConfigureDedicatedInterface;

